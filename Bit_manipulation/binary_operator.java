public class binary_operator {
    public static void main(String[] args){

        // Binary and operator (&)
        System.out.println(5&6); //

        // Binary or operator (|)
        System.out.println(5|6); // 

        // Binary xor operator (^)
        System.out.println(5^6);  //

        // Binary one's complement
        System.out.println(~5);  //

        // Binary Left shift (<<)
        System.out.println(5<<2);

        // Binary right shift (>>)
        System.out.println(5>>2);


    }   
}
